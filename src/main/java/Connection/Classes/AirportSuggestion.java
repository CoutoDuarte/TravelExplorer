package Connection.Classes;

public class AirportSuggestion {
    public String code;
    public String name;
    public String city;
    public String label;

    public AirportSuggestion(String code, String name, String city, String label) {
        this.code = code;
        this.name = name;
        this.city = city;
        this.label = label;
    }
}
